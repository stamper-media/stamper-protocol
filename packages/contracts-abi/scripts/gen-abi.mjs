#!/usr/bin/env node
// Generates src/abis.gen.ts from contracts/out (forge build artefacts) and src/deployments.gen.ts from
// contracts/deployments/{anvil,calibration,mainnet}.json. Equivalent of the @wagmi/cli foundry plugin, without
// the dependency (IMPLEMENTATION-PLAN WP-01). Run via `pnpm --filter @stamper/contracts-abi generate`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(pkg, "..", "..", "contracts");
const out = join(contracts, "out");

/** [exportName, solFile, contractName] */
const targets = [
  ["stampRegistryAbi", "StampRegistry.sol", "StampRegistry"],
  ["stampResolverAbi", "StampResolver.sol", "StampResolver"],
  ["pdpVerifierAbi", "IPDPVerifier.sol", "IPDPVerifier"],
  ["fwssAbi", "IFWSS.sol", "IFWSS"],
  ["fwssStateViewAbi", "IFWSSStateView.sol", "IFWSSStateView"],
  ["mockPdpVerifierAbi", "MockPDPVerifier.sol", "MockPDPVerifier"],
  ["mockFwssAbi", "MockFWSS.sol", "MockFWSS"],
  ["mockStateViewAbi", "MockStateView.sol", "MockStateView"],
];

let abis = "// GENERATED by scripts/gen-abi.mjs from contracts/out. Do not edit.\n";
for (const [name, file, contract] of targets) {
  const path = join(out, file, `${contract}.json`);
  if (!existsSync(path)) {
    console.error(`missing ${path}: run \`forge build --root contracts\` first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(path, "utf8"));
  abis += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(join(pkg, "src", "abis.gen.ts"), abis);

const chains = { anvil: 31337, calibration: 314159, mainnet: 314 };
const found = {};
for (const [file, chainId] of Object.entries(chains)) {
  const path = join(contracts, "deployments", `${file}.json`);
  if (!existsSync(path)) continue;
  const d = JSON.parse(readFileSync(path, "utf8"));
  if (d.chainId !== chainId) {
    console.error(`${path}: chainId ${d.chainId} != ${chainId}`);
    process.exit(1);
  }
  found[chainId] = d;
}
writeFileSync(
  join(pkg, "src", "deployments.gen.ts"),
  "// GENERATED by scripts/gen-abi.mjs from contracts/deployments/*.json. Do not edit.\n" +
    `export const generatedDeployments = ${JSON.stringify(found, null, 2)} as const;\n`,
);
console.log(`abis: ${targets.length}, deployments: ${Object.keys(found).join(", ") || "none"}`);
